"""ORM metadata must match the migrated schema, so autogenerate can never silently drop indexes or the vector column.

Regression for the drift where `articles.search_vector`, `document_chunks.search_vector`, `document_chunks.embedding`
and their GIN / partial indexes existed only in raw-SQL migrations: `alembic check` failed and a routine
`alembic revision --autogenerate` proposed DROP INDEX / DROP COLUMN (an earlier autogenerated revision already dropped
`ix_articles_topic` this way).
"""
from __future__ import annotations

import asyncio

from alembic.autogenerate import compare_metadata
from alembic.migration import MigrationContext
from sqlalchemy import select

from app.db.base import Base
from app.models.architecture import DocumentChunk
from app.models.content import Article


def test_metadata_matches_migrated_database(db_engine) -> None:
    def diff(sync_conn):
        ctx = MigrationContext.configure(sync_conn, opts={"compare_type": True, "compare_server_default": True})
        return compare_metadata(ctx, Base.metadata)

    async def run():
        async with db_engine.connect() as conn:
            return await conn.run_sync(diff)

    assert asyncio.run(run()) == []


def test_raw_sql_indexes_and_columns_are_declared() -> None:
    articles = {i.name for i in Article.__table__.indexes}
    chunks = {i.name for i in DocumentChunk.__table__.indexes}
    assert {"ix_articles_search_vector", "ix_articles_title_trgm"} <= articles
    assert {"ix_document_chunks_search_vector", "ix_document_chunks_embedding_model"} <= chunks
    assert {"search_vector", "embedding"} <= set(DocumentChunk.__table__.columns.keys())
    assert "search_vector" in Article.__table__.columns


def test_generated_and_vector_columns_are_never_loaded_or_written_by_the_orm() -> None:
    article_sql = str(select(Article))
    chunk_sql = str(select(DocumentChunk))
    assert "search_vector" not in article_sql
    assert "embedding," not in chunk_sql and "search_vector" not in chunk_sql and "embedding_model" in chunk_sql
    insert_cols = {c.name for c in DocumentChunk.__table__.columns if c.computed is None}
    assert "search_vector" not in insert_cols  # generated column: never in an INSERT
